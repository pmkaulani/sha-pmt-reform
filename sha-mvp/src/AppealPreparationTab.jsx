import { useState } from "react";

const GROUNDS = [
  ["household_details", "Household or dependant details are incorrect"],
  ["income_or_liquidity", "Income, M-Pesa activity or retained balance is misunderstood"],
  ["asset_or_land", "An asset, vehicle or land detail is incorrect or incomplete"],
  ["deduction_missing", "A deduction, expense or vulnerability was not considered"],
  ["identity_or_linkage", "Records may have been linked to the wrong person or household"],
  ["other", "Another reason"],
];

const styles = {
  panel: { padding: 18, background: "#FFFFFF", border: "1px solid #E2E8F0", borderRadius: 10, display: "grid", gap: 14 },
  heading: { fontSize: 14, fontWeight: 700, color: "#0F172A", marginBottom: 4 },
  label: { display: "block", fontSize: 11, fontWeight: 700, letterSpacing: "0.4px", textTransform: "uppercase", color: "#64748B", marginBottom: 6 },
  textarea: { width: "100%", padding: 12, border: "1px solid #CBD5E1", borderRadius: 8, fontSize: 13, fontFamily: "inherit", resize: "vertical", color: "#0F172A" },
  button: { padding: "11px 16px", border: 0, borderRadius: 7, background: "#0284C7", color: "#FFFFFF", fontWeight: 700, fontSize: 13, cursor: "pointer" },
};

function money(value) {
  const amount = Number(value);
  return Number.isFinite(amount) ? amount.toLocaleString("en-KE") : "Not available";
}

export default function AppealPreparationTab({ results }) {
  const [grounds, setGrounds] = useState([]);
  const [explanation, setExplanation] = useState("");
  const [corrections, setCorrections] = useState("");
  const [requestedAction, setRequestedAction] = useState("human_review");
  const [prepared, setPrepared] = useState(null);
  const [error, setError] = useState("");

  const toggleGround = (value) => {
    setGrounds((current) =>
      current.includes(value) ? current.filter((item) => item !== value) : [...current, value]
    );
    setPrepared(null);
  };

  const prepareDraft = () => {
    if (grounds.length === 0) {
      setError("Select at least one reason for challenging the assessment.");
      return;
    }
    if (explanation.trim().length < 20) {
      setError("Please explain the issue in at least 20 characters.");
      return;
    }

    const now = new Date();
    const suffix =
      typeof crypto !== "undefined" && crypto.randomUUID
        ? crypto.randomUUID().slice(0, 8).toUpperCase()
        : Math.random().toString(36).slice(2, 10).toUpperCase();
    const reference = "SHA-CH-" + now.toISOString().slice(0, 10).replace(/-/g, "") + "-" + suffix;
    const current = results.current || {};
    const proposed = results.next || {};
    const input = results.d || {};

    setPrepared({
      reference,
      createdAt: now.toISOString(),
      status: "DRAFT_PREPARED_LOCALLY_NOT_SUBMITTED",
      assessmentReference: results.auditRecord?.assessmentId || null,
      grounds: grounds.map((code) => ({
        code,
        label: (GROUNDS.find((item) => item[0] === code) || [code, code])[1],
      })),
      explanation: explanation.trim(),
      corrections: corrections.trim(),
      requestedAction,
      snapshot: {
        county: input.county || null,
        householdSize: input.householdSize ?? null,
        headAge: input.headAge ?? null,
        illustrativeBaselineMonthlyKsh: current.monthly ?? null,
        proposedRulesEngineMonthlyKsh: proposed.monthlyContribution ?? proposed.monthly ?? null,
        proposedAdjustedGrossIncomeKsh: proposed.adjustedGrossIncome ?? null,
        deductions: (proposed.deductions || []).map((item) => ({
          name: item.name,
          amountKsh: item.amount,
          reason: item.reason,
        })),
      },
    });
    setError("");
  };

  const downloadDraft = () => {
    if (!prepared) return;
    const requested = {
      human_review: "A human review of the assessment",
      correct_records: "Correction of household or source records",
      explanation: "A clear explanation of the calculation",
      reassessment: "A reassessment after corrections",
    }[prepared.requestedAction] || prepared.requestedAction;
    const deductions = prepared.snapshot.deductions.length
      ? prepared.snapshot.deductions.map((item) =>
          "- " + item.name + ": KSh " + money(item.amountKsh) + " — " + (item.reason || "")
        ).join("\n")
      : "- No deduction entries were generated by this demonstration.";
    const statement = [
      "SHA MEANS-TESTING ASSESSMENT CHALLENGE — PREPARATION DRAFT",
      "Reference: " + prepared.reference,
      "Prepared: " + prepared.createdAt,
      "Status: NOT SUBMITTED",
      "",
      "IMPORTANT: This is a locally generated preparation document. It has not been sent to SHA, no case has been opened, and no review deadline has started.",
      "",
      "Assessment reference: " + (prepared.assessmentReference || "Not available"),
      "County entered: " + (prepared.snapshot.county || "Not provided"),
      "Household size entered: " + (prepared.snapshot.householdSize ?? "Not provided"),
      "Age of household head entered: " + (prepared.snapshot.headAge ?? "Not provided"),
      "",
      "REASONS FOR CHALLENGE",
      ...prepared.grounds.map((item) => "- " + item.label),
      "",
      "EXPLANATION",
      prepared.explanation,
      "",
      "CORRECTIONS / SUPPORTING INFORMATION TO PROVIDE",
      prepared.corrections || "Not provided. Add relevant supporting information before lodging the challenge.",
      "",
      "REQUESTED ACTION",
      requested,
      "",
      "PROTOTYPE CALCULATION SNAPSHOT — NOT AN OFFICIAL SHA DECISION",
      "Illustrative baseline monthly amount: KSh " + money(prepared.snapshot.illustrativeBaselineMonthlyKsh),
      "Proposed rules-engine monthly amount: KSh " + money(prepared.snapshot.proposedRulesEngineMonthlyKsh),
      "Proposed adjusted gross income: KSh " + money(prepared.snapshot.proposedAdjustedGrossIncomeKsh),
      "Displayed deduction lines:",
      deductions,
      "",
      "NEXT STEP",
      "Review this statement, add relevant supporting documents, and lodge the challenge through SHA's official Contributions Appeal channel. The prototype does not transmit it.",
      "",
      "The prototype does not upload documents, transmit data, or create a real SHA case.",
    ].join("\n");

    const blob = new Blob([statement], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = prepared.reference + "-challenge-draft.txt";
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
  };

  return (
    <div style={{ display: "grid", gap: 22, maxWidth: 900 }}>
      <div>
        <div style={{ fontFamily: "Inter, sans-serif", fontSize: 24, fontWeight: 700, color: "#0F172A", marginBottom: 8 }}>
          Prepare a challenge to an assessment
        </div>
        <div style={{ fontSize: 14, color: "#64748B", lineHeight: 1.6 }}>
          A member should be able to understand what was used, identify what is wrong, explain the issue and ask for a human review. This screen prepares a written statement using the current demonstration results.
        </div>
      </div>

      <div style={{ padding: 16, background: "#FFFBEB", border: "1px solid #FDE68A", borderRadius: 10 }}>
        <div style={{ fontSize: 13, fontWeight: 700, color: "#B45309", marginBottom: 5 }}>Prototype boundary — not a live submission</div>
        <div style={{ fontSize: 13, color: "#0F172A", lineHeight: 1.55 }}>
          Nothing on this screen is sent to SHA. It does not open an appeal case, upload evidence, or start an official review period. Downloading the statement gives the member a draft to review and lodge through SHA's existing Contributions Appeal channel.
        </div>
      </div>

      <div style={styles.panel}>
        <div style={styles.heading}>1. Check the demonstration figures</div>
        <div className="grid-2">
          <div style={{ padding: 14, background: "#F8FAFC", borderRadius: 8 }}>
            <div style={{ fontSize: 11, fontWeight: 700, color: "#64748B", textTransform: "uppercase", marginBottom: 5 }}>Illustrative baseline</div>
            <div style={{ fontSize: 24, fontWeight: 800, color: "#DC2626" }}>KSh {money(results.current?.monthly)}</div>
            <div style={{ fontSize: 11, color: "#64748B" }}>Prototype comparison only</div>
          </div>
          <div style={{ padding: 14, background: "#F8FAFC", borderRadius: 8 }}>
            <div style={{ fontSize: 11, fontWeight: 700, color: "#64748B", textTransform: "uppercase", marginBottom: 5 }}>Proposed rules engine</div>
            <div style={{ fontSize: 24, fontWeight: 800, color: "#059669" }}>KSh {money(results.next?.monthlyContribution ?? results.next?.monthly)}</div>
            <div style={{ fontSize: 11, color: "#64748B" }}>Not an official SHA determination</div>
          </div>
        </div>
        <div style={{ fontSize: 12, color: "#64748B", marginTop: 10, lineHeight: 1.5 }}>
          The two values above come from this prototype. They must not be represented as a member's actual SHA premium or an official decision.
        </div>
      </div>

      <div style={styles.panel}>
        <div style={styles.heading}>2. What do you believe is incorrect?</div>
        <div style={{ display: "grid", gap: 10 }}>
          {GROUNDS.map(([value, label]) => (
            <label key={value} style={{
              display: "flex", gap: 10, alignItems: "flex-start", padding: 11,
              border: "1px solid " + (grounds.includes(value) ? "#BAE6FD" : "#E2E8F0"),
              borderRadius: 8, background: grounds.includes(value) ? "#F0F9FF" : "#FFFFFF", cursor: "pointer"
            }}>
              <input type="checkbox" checked={grounds.includes(value)} onChange={() => toggleGround(value)} style={{ marginTop: 3 }} />
              <span style={{ fontSize: 13, color: "#0F172A", lineHeight: 1.45 }}>{label}</span>
            </label>
          ))}
        </div>
      </div>

      <div style={styles.panel}>
        <div style={styles.heading}>3. Explain the issue</div>
        <div>
          <label style={styles.label}>What happened, and why do you think the assessment is wrong?</label>
          <textarea value={explanation} onChange={(event) => { setExplanation(event.target.value); setPrepared(null); }}
            rows={5} maxLength={3000}
            placeholder="For example: the household size includes a dependant who no longer lives with me, or the balance shown includes money collected for a chama..."
            style={styles.textarea} />
          <div style={{ fontSize: 11, color: "#64748B", textAlign: "right", marginTop: 4 }}>{explanation.length}/3000</div>
        </div>
        <div>
          <label style={styles.label}>What information should be corrected, or what supporting evidence will you provide?</label>
          <textarea value={corrections} onChange={(event) => { setCorrections(event.target.value); setPrepared(null); }}
            rows={4} maxLength={3000}
            placeholder="List corrected information and supporting items you can provide, such as household records, statements, receipts or relevant letters..."
            style={styles.textarea} />
        </div>
        <div>
          <label style={styles.label}>What outcome are you requesting?</label>
          <select value={requestedAction} onChange={(event) => { setRequestedAction(event.target.value); setPrepared(null); }}
            style={{ width: "100%", padding: 12, border: "1px solid #CBD5E1", borderRadius: 8, fontSize: 13, background: "#FFFFFF", color: "#0F172A" }}>
            <option value="human_review">A human review of the assessment</option>
            <option value="correct_records">Correction of household or source records</option>
            <option value="explanation">A clear explanation of the calculation</option>
            <option value="reassessment">A reassessment after corrections</option>
          </select>
        </div>
        {error && <div role="alert" style={{ fontSize: 12, color: "#DC2626" }}>{error}</div>}
        <div style={{ display: "flex", gap: 10, flexWrap: "wrap", alignItems: "center" }}>
          <button onClick={prepareDraft} style={styles.button}>Prepare challenge statement</button>
          <span style={{ fontSize: 11, color: "#64748B" }}>No case is submitted by this action.</span>
        </div>
      </div>

      {prepared && (
        <div style={{ padding: 18, background: "#ECFDF5", border: "1px solid #A7F3D0", borderRadius: 10 }}>
          <div style={{ fontSize: 14, fontWeight: 700, color: "#047857", marginBottom: 5 }}>Challenge statement prepared locally</div>
          <div style={{ fontSize: 12, color: "#0F172A", marginBottom: 12 }}>Reference: <strong>{prepared.reference}</strong> · Status: <strong>NOT SUBMITTED</strong></div>
          <button onClick={downloadDraft} style={{ padding: "10px 14px", border: 0, borderRadius: 7, background: "#0F172A", color: "#FFFFFF", fontWeight: 700, fontSize: 13, cursor: "pointer" }}>
            Download challenge statement (.txt)
          </button>
          <div style={{ fontSize: 12, color: "#0F172A", lineHeight: 1.55, marginTop: 12 }}>
            Before lodging it, review the draft and add the documents that support your correction. The meeting notes identify this route: *147# → Kenyan Citizen → enter ID → Contributions Appeal. Confirm the current route with SHA before using it. This prototype does not transmit the statement.
          </div>
        </div>
      )}
    </div>
  );
}
